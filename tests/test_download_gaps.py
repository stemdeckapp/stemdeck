"""URL normalisation, playlist validation, and the download progress hooks.

Three uncovered areas in download.py, all on the path between a user pasting a
link and a job starting.

normalize_youtube_url is the one that decides whether a paste works at all: a
share link, a Music link, a mobile link, a `live/` VOD and a radio-mix URL all
have to resolve to the same watch URL, and anything it fails to recognise is
handed to yt-dlp as typed.

The progress hooks are the cancellation checkpoint during a download -- yt-dlp
calls them per chunk, and raising is the only way to abort a fetch already in
flight. They are closures, so they are driven here through a stub YoutubeDL
that calls them the way yt-dlp does.
"""

from __future__ import annotations

import pytest

from app.core.models import Job, JobCancelled
from app.pipeline import download as dl_mod
from app.pipeline.download import InvalidPlaylistURL

VID = "dQw4w9WgXcQ"
WATCH = f"https://www.youtube.com/watch?v={VID}"


# --------------------------------------------------------------------------
# normalize_youtube_url
# --------------------------------------------------------------------------


@pytest.mark.parametrize(
    "url, why",
    [
        (f"https://youtu.be/{VID}", "a share link"),
        (f"https://youtu.be/{VID}?t=42", "a share link with a timestamp"),
        (f"https://m.youtube.com/watch?v={VID}", "a mobile link"),
        (f"https://music.youtube.com/watch?v={VID}", "a YouTube Music link"),
        (f"https://www.youtube-nocookie.com/watch?v={VID}", "a nocookie embed"),
        (f"https://youtube.com/watch?v={VID}&list=PL123&index=3", "a link inside a playlist"),
        (f"https://www.youtube.com/watch?v={VID}&t=90s", "a link with a start time"),
    ],
)
def test_every_shape_of_youtube_link_resolves_to_the_same_video(url, why):
    assert dl_mod.normalize_youtube_url(url) == WATCH, why


def test_a_radio_mix_link_falls_back_to_its_seed_video():
    """An autogenerated RD... mix has no stable playlist to import, but the
    video it was seeded from is right there in the id."""
    assert dl_mod.normalize_youtube_url(f"https://www.youtube.com/watch?list=RD{VID}") == WATCH


def test_a_radio_mix_with_no_derivable_seed_is_left_alone():
    url = "https://www.youtube.com/watch?list=RDshort"
    assert dl_mod.normalize_youtube_url(url) == url


@pytest.mark.parametrize(
    "url",
    [
        "https://soundcloud.com/artist/track",
        "https://example.com/watch?v=" + VID,
        "https://www.youtube.com/playlist?list=PL1234567890",
        "not a url at all",
        "",
    ],
)
def test_anything_else_is_handed_through_untouched(url):
    """yt-dlp surfaces its own error for these; rewriting a link we do not
    understand would turn a clear message into a confusing one."""
    assert dl_mod.normalize_youtube_url(url) == url


def test_a_youtu_be_path_that_is_not_a_video_id_is_left_alone():
    url = "https://youtu.be/not-an-id-at-all-way-too-long"
    assert dl_mod.normalize_youtube_url(url) == url


def test_normalisation_never_raises_on_a_url_it_cannot_parse(monkeypatch):
    """This runs on user-pasted text. A parse failure has to read as "not one
    of ours", not take the submit endpoint down."""
    import urllib.parse

    def _boom(_url):
        raise ValueError("unparseable")

    monkeypatch.setattr(urllib.parse, "urlparse", _boom)

    assert dl_mod.normalize_youtube_url("https://youtu.be/x") == "https://youtu.be/x"


