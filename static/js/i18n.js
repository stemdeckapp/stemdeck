// i18n engine: English, Polish, Japanese, Simplified Chinese, German,
// Portuguese, Indonesian.
//
// Architecture:
// - Flat dot-path keys (e.g. "nav.library") into per-language string tables.
// - t(key, vars) looks up the current language, falling back to English for
//   any missing key so a partial translation can never render blank/undefined
//   text -- a missing key is a a silent English fallback, not a crash.
// - {placeholders} in a template are replaced from `vars` via a single
//   template-string mechanism (not concatenated clauses), so word order can
//   differ per language without the sentence falling apart grammatically.
// - applyTranslations(root) walks data-i18n / data-i18n-title /
//   data-i18n-aria-label / data-i18n-placeholder attributes in the static DOM
//   and sets the corresponding property. JS-generated UI (settings modal,
//   notifications, job status, etc.) calls t() directly wherever it builds
//   its own strings.
// - Language choice is a purely cosmetic, client-only preference (no backend
//   behavior depends on it), so it's persisted via storeGet/storeSet
//   (static/js/utils.js) under "stemdeck.language", the same convention as
//   other UI-only preferences (stemdeck.catalog.collapsed, selected stems).

import { storeGet, storeSet } from "./utils.js";

export const LANGUAGES = [
  { code: "en", flag: "🇬🇧", name: "English" },
  { code: "pl", flag: "🇵🇱", name: "Polski" },
  { code: "ja", flag: "🇯🇵", name: "日本語" },
  { code: "zh-Hans", flag: "🇨🇳", name: "简体中文" },
  { code: "de", flag: "🇩🇪", name: "Deutsch" },
  { code: "pt", flag: "🇧🇷", name: "Português" },
  { code: "id", flag: "🇮🇩", name: "Bahasa Indonesia" },
];
const SUPPORTED_CODES = new Set(LANGUAGES.map((l) => l.code));
const DEFAULT_LANG = "en";

let _lang = DEFAULT_LANG;
const _listeners = new Set();

function _detectDefault() {
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
  const lower = nav.toLowerCase();
  if (lower.startsWith("pl")) return "pl";
  if (lower.startsWith("ja")) return "ja";
  // Simplified Chinese: zh-CN, zh-Hans, zh-SG, or bare "zh" (assume simplified
  // unless it's explicitly a traditional-script region, which we don't ship).
  if (lower.startsWith("zh")) return "zh-Hans";
  if (lower.startsWith("de")) return "de";
  // Portuguese: pt-BR, pt-PT, or bare "pt" all map to the single pt table
  // (written in Brazilian Portuguese, the more widely used variant).
  if (lower.startsWith("pt")) return "pt";
  if (lower.startsWith("id")) return "id";
  return "en";
}

export async function initI18n() {
  const stored = await storeGet("stemdeck.language", null);
  _lang = stored && SUPPORTED_CODES.has(stored) ? stored : _detectDefault();
  document.documentElement.lang = _lang === "zh-Hans" ? "zh-Hans" : _lang;
  return _lang;
}

export function getLanguage() {
  return _lang;
}

export async function setLanguage(code) {
  if (!SUPPORTED_CODES.has(code) || code === _lang) return;
  _lang = code;
  document.documentElement.lang = code === "zh-Hans" ? "zh-Hans" : code;
  await storeSet("stemdeck.language", code);
  applyTranslations(document);
  for (const fn of _listeners) {
    try {
      fn(code);
    } catch (e) {
      console.warn("[i18n] language-change listener failed:", e);
    }
  }
}

// Called by any part of the app that needs to re-render JS-generated content
// (not just static DOM) when the language changes -- e.g. the settings modal
// re-rendering itself in place, or the notifications panel re-rendering its
// currently-open list.
export function onLanguageChange(fn) {
  _listeners.add(fn);
  return () => _listeners.delete(fn);
}

function _interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, key) => (key in vars ? String(vars[key]) : m));
}

export function t(key, vars) {
  const table = TRANSLATIONS[_lang] || TRANSLATIONS[DEFAULT_LANG];
  const str = table[key] ?? TRANSLATIONS[DEFAULT_LANG][key];
  if (str == null) {
    console.warn(`[i18n] missing key "${key}"`);
    return key;
  }
  return _interpolate(str, vars);
}

// Plural selection. English/German/Portuguese: two buckets (one/other) is
// standard. Japanese/Chinese/Indonesian have no grammatical plural at all, so
// "other" covers every count -- the key exists for interface symmetry, not
// because those languages need it (only ".other" is ever defined for them,
// and the fallback chain below finds it regardless of computed form). Polish
// needs three (one / few / many) per its numeral rules.
export function plural(key, count, vars) {
  const table = TRANSLATIONS[_lang] || TRANSLATIONS[DEFAULT_LANG];
  let form;
  if (_lang === "pl") {
    const n = Math.abs(count);
    const mod10 = n % 10;
    const mod100 = n % 100;
    if (n === 1) form = "one";
    else if (mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14)) form = "few";
    else form = "many";
  } else {
    form = count === 1 ? "one" : "other";
  }
  const fullKey = `${key}.${form}`;
  // Prefer this language's own "other" bucket before ever falling back to
  // English -- languages with no grammatical plural (Japanese, Chinese) only
  // define ".other", so a singular count must resolve there, not to an
  // English ".one" string mixed into otherwise-translated text.
  const str =
    table[fullKey] ??
    table[`${key}.other`] ??
    TRANSLATIONS[DEFAULT_LANG][fullKey] ??
    TRANSLATIONS[DEFAULT_LANG][`${key}.other`];
  if (str == null) {
    console.warn(`[i18n] missing plural key "${fullKey}"`);
    return key;
  }
  return _interpolate(str, { count, ...vars });
}

export function applyTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  scope.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  const titleKey = document.documentElement.getAttribute("data-i18n-doctitle");
  if (titleKey) document.title = t(titleKey);
  applyStemRowAriaLabels(scope);
}

// The stem-list rows (static/index.html's .stem-list) carry their display
// name via a plain data-i18n span (see applyTranslations above), but their
// Mute/Solo/Solo-only aria-labels are composed from that same name via a
// template ("Mute {name}"), not a flat string -- so they need this dedicated
// pass rather than the generic data-i18n-aria-label mechanism, which only
// supports a fixed key with no per-element variable.
function applyStemRowAriaLabels(scope) {
  scope.querySelectorAll(".stem-list > span[data-stem]").forEach((row) => {
    const stemKey = row.getAttribute("data-stem");
    const name = t(`stem.${stemKey}`);
    const mute = row.querySelector(".stem-mute");
    if (mute) mute.setAttribute("aria-label", t("aria.mute", { name }));
    const solo = row.querySelector(".stem-solo");
    if (solo) solo.setAttribute("aria-label", t("aria.solo", { name }));
    const monitor = row.querySelector(".stem-monitor");
    if (monitor) monitor.setAttribute("aria-label", t("aria.soloOnly", { name }));
  });
}

